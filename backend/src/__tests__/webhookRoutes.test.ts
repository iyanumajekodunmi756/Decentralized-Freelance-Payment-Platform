import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import express from "express";
import type { Server } from "node:http";

const h = vi.hoisted(() => ({
  create: vi.fn(),
  findMany: vi.fn(),
  findUnique: vi.fn(),
  delete: vi.fn(),
  userFindUnique: vi.fn(),
}));

vi.mock("../db", () => ({
  prisma: {
    webhookSubscription: {
      create: h.create,
      findMany: h.findMany,
      findUnique: h.findUnique,
      delete: h.delete,
    },
    user: { findUnique: h.userFindUnique },
  },
}));

let baseUrl: string;
let server: Server;

beforeAll(async () => {
  const { webhooksRouter } = await import("../routes/webhooks");
  const { errorHandler } = await import("../middleware/errorHandler");
  const app = express();
  app.use(express.json());
  app.use("/api/webhooks", webhooksRouter);
  app.use(errorHandler);

  await new Promise<void>((resolve) => {
    server = app.listen(0, "127.0.0.1", resolve);
  });
  const address = server.address();
  if (address === null || typeof address === "string") throw new Error("no port assigned");
  baseUrl = `http://127.0.0.1:${address.port}`;
});

afterAll(async () => {
  await new Promise<void>((resolve, reject) =>
    server.close((err) => (err ? reject(err) : resolve())),
  );
});

beforeEach(() => {
  vi.clearAllMocks();
});

describe("Webhook API routes (issue #313)", () => {
  it("POST /api/webhooks registers a destination URL and returns 201 with generated secret", async () => {
    h.create.mockResolvedValue({
      id: "sub-123",
      url: "https://my-app.com/webhooks",
      secret: "autogenerated-secret-key-321",
      events: ["*"],
      isActive: true,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    });

    const res = await fetch(`${baseUrl}/api/webhooks`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ url: "https://my-app.com/webhooks" }),
    });

    expect(res.status).toBe(201);
    const body = (await res.json()) as { id?: string; url?: string };
    expect(body.id).toBe("sub-123");
    expect(body.url).toBe("https://my-app.com/webhooks");
    expect(h.create).toHaveBeenCalledWith(
      expect.objectContaining({
        data: expect.objectContaining({
          url: "https://my-app.com/webhooks",
          events: ["*"],
        }),
      }),
    );
  });

  it("generates a separate 32-byte secret for each omitted secret", async () => {
    const secrets: string[] = [];
    for (const suffix of ["first", "second"]) {
      h.create.mockImplementationOnce(async ({ data }) => data);
      const response = await fetch(`${baseUrl}/api/webhooks`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ url: `https://example.com/${suffix}` }),
      });
      expect(response.status).toBe(201);
      const data = (await response.json()) as { secret: string };
      secrets.push(data.secret);
    }
    expect(secrets).toEqual(secrets.map(() => expect.stringMatching(/^[a-f0-9]{64}$/)));
    expect(new Set(secrets).size).toBe(2);
  });

  it("POST /api/webhooks rejects an invalid URL with 400", async () => {
    const res = await fetch(`${baseUrl}/api/webhooks`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ url: "not-a-valid-url" }),
    });

    expect(res.status).toBe(400);
    expect(h.create).not.toHaveBeenCalled();
  });

  it("GET /api/webhooks lists existing webhook subscriptions", async () => {
    h.findMany.mockResolvedValue([
      { id: "sub-1", url: "https://a.com/hook", events: ["*"], isActive: true },
      { id: "sub-2", url: "https://b.com/hook", events: ["milestone_released"], isActive: true },
    ]);

    const res = await fetch(`${baseUrl}/api/webhooks`);
    expect(res.status).toBe(200);
    const list = (await res.json()) as Array<{ id?: string }>;
    expect(list).toHaveLength(2);
    expect(list[0].id).toBe("sub-1");
  });

  it("GET /api/webhooks/:id returns subscription details or 404", async () => {
    h.findUnique.mockResolvedValueOnce({
      id: "sub-1",
      url: "https://a.com/hook",
      events: ["*"],
      isActive: true,
    });

    const okRes = await fetch(`${baseUrl}/api/webhooks/sub-1`);
    expect(okRes.status).toBe(200);
    const body = (await okRes.json()) as { id?: string };
    expect(body.id).toBe("sub-1");

    h.findUnique.mockResolvedValueOnce(null);
    const notFoundRes = await fetch(`${baseUrl}/api/webhooks/unknown-id`);
    expect(notFoundRes.status).toBe(404);
  });

  it("DELETE /api/webhooks/:id removes the subscription", async () => {
    h.findUnique.mockResolvedValueOnce({ id: "sub-1" });
    h.delete.mockResolvedValueOnce({ id: "sub-1" });

    const res = await fetch(`${baseUrl}/api/webhooks/sub-1`, { method: "DELETE" });
    expect(res.status).toBe(200);
    const body = (await res.json()) as { deleted?: boolean };
    expect(body.deleted).toBe(true);
    expect(h.delete).toHaveBeenCalledWith({ where: { id: "sub-1" } });
  });
});
